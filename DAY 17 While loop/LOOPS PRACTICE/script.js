// QUESTION NO 1
console.log("100 ---- 600 --- 20 (GAP)");

console.log("Using for loop");
let i1;
for(i1 = 100 ; i1 <= 600 ; i1+=20){
    console.log(i1);
}

console.log("USing While loop");
let i2 = 100;
while( i2 <= 600 ){
    console.log(i2);
    i2+=20;
}

console.log("USing do while loop");
let i3 = 100;
do{
    console.log(i3);
    i3+=20
}while( i3 <= 600);



